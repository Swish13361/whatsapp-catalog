function getStoredLanguage() {
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY) === "zh-CN" ? "zh-CN" : "en";
  } catch {
    return "en";
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getStoredLanguage);
  useEffect(() => {
    const previousLanguage = document.documentElement.lang;
    document.documentElement.lang = language;
    return () => {
      document.documentElement.lang = previousLanguage;
    };
  }, [language]);
  const changeLanguage = useCallback((nextLanguage) => {
    const next = nextLanguage === "zh-CN" ? "zh-CN" : "en";
    setLanguage(next);
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    } catch {
      // The selected language still applies for this session if storage is unavailable.
    }
  }, []);
  const t = useCallback((key, values = {}) => {
    const template = translations[language][key] ?? translations.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
  }, [language]);
  const value = useMemo(() => ({ language, setLanguage: changeLanguage, t }), [changeLanguage, language, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function LanguageSwitcher() {
  const { language, setLanguage, t } = useLanguage();

  return (
    <label className="language-picker">
      <span className="language-picker-label">{t("language")}</span>
      <select value={language} onChange={(event) => setLanguage(event.target.value)} aria-label={t("language")}>
        <option value="en">English</option>
        <option value="zh-CN">中文（简体）</option>
      </select>
    </label>
  );
}






